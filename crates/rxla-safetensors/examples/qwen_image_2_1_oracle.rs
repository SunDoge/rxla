use clap::Parser;
use rxla_core::{Buffer, CacheLimits, Client, Compiler, DType};
use rxla_models::qwen_image_2_1::{QwenImage21Config, qwen_image_2_1_transformer};
use rxla_nn::{Cx, Model, ModelInput};
use rxla_safetensors::SafeTensors;
use std::path::PathBuf;

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

#[derive(Parser)]
#[command(about = "Compare RXLA Qwen-Image-2.1 with a PyTorch oracle")]
struct Args {
    /// Use the tiny grouped-W8 topology and a quantized checkpoint.
    #[arg(long)]
    w8: bool,
    /// Use the complete official 32-layer grouped-W8 topology.
    #[arg(long, conflicts_with = "w8")]
    official_w8: bool,
    /// Run affine projections in BF16, as the official-size path does.
    #[arg(long, conflicts_with = "f32_compute")]
    bf16_compute: bool,
    /// Run affine projections in F32 for architecture diagnostics.
    #[arg(long)]
    f32_compute: bool,
    /// Override the maximum accepted absolute error.
    #[arg(long)]
    atol: Option<f32>,
    /// Trusted PJRT plugin shared library.
    plugin: PathBuf,
    /// weights.safetensors generated by benchmarks/qwen_image_2_1_oracle.py.
    weights: PathBuf,
    /// oracle.safetensors generated by benchmarks/qwen_image_2_1_oracle.py.
    oracle: PathBuf,
}

fn upload(client: &Client, checkpoint: &mut SafeTensors, name: &str) -> Result<Buffer> {
    let tensor = checkpoint.read_f32(name)?;
    Ok(client.buffer(&tensor.shape, &tensor.values)?)
}

fn run(args: Args) -> Result<()> {
    let client = unsafe { Client::load(args.plugin) }?;
    let (mut config, image_tokens, image_channels, context_tokens, context_width) =
        if args.official_w8 {
            (QwenImage21Config::official_w8(2, 2), 4, 64, 8, 4096)
        } else if args.w8 {
            (QwenImage21Config::tiny_w8(2, 3), 6, 8, 5, 24)
        } else {
            (QwenImage21Config::tiny(2, 3), 6, 8, 5, 24)
        };
    if args.bf16_compute {
        config = config.compute_dtype(DType::BF16);
    } else if args.f32_compute {
        config = config.compute_dtype(DType::F32);
    }
    let model = Model::new(|cx: Cx, image, timestep, context| {
        qwen_image_2_1_transformer(cx, &image, &timestep, &context, &config)
    })
    .inputs((
        ModelInput::new([1, image_tokens, image_channels]),
        ModelInput::new([1]),
        ModelInput::new([1, context_tokens, context_width]),
    ))
    .trace()?;
    let mut weights = SafeTensors::open(args.weights)?;
    let parameters = weights.load_parameter_schema(&client, model.schema())?;
    let compiled = model.compile(&mut Compiler::new(client.clone(), CacheLimits::default()))?;
    let runner = compiled.bind_parameters(parameters.bindings())?;
    let mut oracle = SafeTensors::open(args.oracle)?;
    let image = upload(&client, &mut oracle, "image")?;
    let timestep = upload(&client, &mut oracle, "timestep")?;
    let context = upload(&client, &mut oracle, "context")?;
    let output: Buffer = runner.run((&image, &timestep, &context))?;
    let actual = output.to_vec::<f32>()?;
    let expected = oracle.read_f32("output")?.values;
    let max_absolute = actual
        .iter()
        .zip(&expected)
        .map(|(&actual, &expected)| (actual - expected).abs())
        .fold(0.0_f32, f32::max);
    let mean_absolute = actual
        .iter()
        .zip(&expected)
        .map(|(&actual, &expected)| f64::from((actual - expected).abs()))
        .sum::<f64>()
        / actual.len() as f64;
    println!(
        "backend={} max_absolute={max_absolute:.9} mean_absolute={mean_absolute:.9} checksum={:.9}",
        client.info()?.platform,
        actual.iter().map(|&value| f64::from(value)).sum::<f64>(),
    );
    let tolerance = args.atol.unwrap_or(if args.official_w8 {
        // Across 32 BF16 blocks, CUDA/XLA and PyTorch accumulate different
        // rounding from their GEMM and attention implementations. The F32
        // diagnostic remains the strict architecture check (< 2e-5).
        if args.f32_compute { 2e-5 } else { 0.1 }
    } else if args.w8 {
        0.02
    } else {
        3e-4
    });
    if max_absolute > tolerance {
        return Err(format!(
            "Qwen-Image-2.1 numerical mismatch: max absolute error {max_absolute}"
        )
        .into());
    }
    Ok(())
}

fn main() -> Result<()> {
    run(Args::parse())
}
