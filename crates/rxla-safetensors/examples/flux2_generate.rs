use clap::Parser;
use image::{Rgb, RgbImage};
use rxla_core::{Buffer, CacheLimits, Client, Compiler};
use rxla_models::{
    flux2::{Flux2Config, Flux2EulerScheduler, flux2_euler_step},
    flux2_autoencoder_decoder,
};
use rxla_nn::{Cx, Model, ModelInput};
use rxla_safetensors::SafeTensors;
use std::path::PathBuf;

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

#[derive(Parser)]
#[command(about = "Generate an image with official FLUX.2 Klein 4B checkpoints")]
struct Args {
    /// Trusted CUDA PJRT plugin.
    plugin: PathBuf,
    /// Official flux-2-klein-4b.safetensors.
    transformer: PathBuf,
    /// Official vae/diffusion_pytorch_model.safetensors.
    vae: PathBuf,
    /// Context/noise file generated by benchmarks/flux2_prompt.py.
    conditioning: PathBuf,
    /// Output PNG path.
    output: PathBuf,
    #[arg(long, default_value_t = 256)]
    height: i64,
    #[arg(long, default_value_t = 256)]
    width: i64,
}

fn upload(client: &Client, checkpoint: &mut SafeTensors, name: &str) -> Result<Buffer> {
    let tensor = checkpoint.read_f32(name)?;
    Ok(client.buffer(&tensor.shape, &tensor.values)?)
}

fn run(args: Args) -> Result<()> {
    if args.height <= 0 || args.width <= 0 || args.height % 16 != 0 || args.width % 16 != 0 {
        return Err("height and width must be positive multiples of 16".into());
    }
    let grid_height = args.height / 16;
    let grid_width = args.width / 16;
    let image_tokens = grid_height * grid_width;
    let client = unsafe { Client::load(&args.plugin) }?;
    let mut conditioning = SafeTensors::open(&args.conditioning)?;
    let context_shape = conditioning
        .info("context")
        .ok_or("conditioning file has no context")?
        .shape
        .clone();
    if context_shape.len() != 3 || context_shape[0] != 1 || context_shape[2] != 7680 {
        return Err("conditioning context must have shape [1, sequence, 7680]".into());
    }
    let context_tokens = i64::try_from(context_shape[1])?;
    let mut sample = upload(&client, &mut conditioning, "image")?;
    let image_ids = upload(&client, &mut conditioning, "image_ids")?;
    let context = upload(&client, &mut conditioning, "context")?;
    let context_ids = upload(&client, &mut conditioning, "context_ids")?;

    let config = Flux2Config::klein_4b();
    let denoise = Model::new(
        |cx: Cx, sample, image_ids, timestep, step_size, context, context_ids| {
            flux2_euler_step(
                cx,
                &sample,
                &image_ids,
                &timestep,
                &step_size,
                &context,
                &context_ids,
                &config,
            )
        },
    )
    .inputs((
        ModelInput::new([1, image_tokens, 128]),
        ModelInput::new([1, image_tokens, 4]),
        ModelInput::new([1]),
        ModelInput::new([1]),
        ModelInput::new([1, context_tokens, 7680]),
        ModelInput::new([1, context_tokens, 4]),
    ))
    .trace()?;
    let mut transformer_checkpoint = SafeTensors::open(&args.transformer)?;
    transformer_checkpoint.validate_parameter_schema(denoise.schema())?;
    let transformer_weights =
        transformer_checkpoint.load_parameter_schema(&client, denoise.schema())?;
    let mut compiler = Compiler::new(client.clone(), CacheLimits::default());
    let compile_started = std::time::Instant::now();
    let denoise = denoise
        .compile(&mut compiler)?
        .bind_parameters(transformer_weights.bindings())?;
    let denoise_compile_ms = compile_started.elapsed().as_secs_f64() * 1e3;

    let schedule = Flux2EulerScheduler::klein_4b(image_tokens as usize)?;
    let denoise_started = std::time::Instant::now();
    for index in 0..4 {
        let step = schedule.step(index)?;
        let timestep = client.buffer(&[1], &[step.timestep])?;
        let step_size = client.buffer(&[1], &[step.next_timestep - step.timestep])?;
        sample = denoise.run((
            &sample,
            &image_ids,
            &timestep,
            &step_size,
            &context,
            &context_ids,
        ))?;
    }
    let denoise_ms = denoise_started.elapsed().as_secs_f64() * 1e3;

    let decoder = Model::new(|cx: Cx, tokens| {
        flux2_autoencoder_decoder(cx, &tokens, grid_height, grid_width)
    })
    .inputs(ModelInput::new([1, image_tokens, 128]))
    .trace()?;
    let mut vae_checkpoint = SafeTensors::open(&args.vae)?;
    vae_checkpoint.validate_parameter_schema(decoder.schema())?;
    let vae_weights = vae_checkpoint.load_parameter_schema(&client, decoder.schema())?;
    let compile_started = std::time::Instant::now();
    let decoder = decoder
        .compile(&mut compiler)?
        .bind_parameters(vae_weights.bindings())?;
    let vae_compile_ms = compile_started.elapsed().as_secs_f64() * 1e3;
    let decode_started = std::time::Instant::now();
    let image: Buffer = decoder.run(&sample)?;
    let values = image.to_vec::<f32>()?;
    let decode_ms = decode_started.elapsed().as_secs_f64() * 1e3;
    let mut output = RgbImage::new(args.width as u32, args.height as u32);
    let (pixels, remainder) = values.as_chunks::<3>();
    if !remainder.is_empty() {
        return Err("decoder output is not RGB-aligned".into());
    }
    for (pixel, channels) in output.pixels_mut().zip(pixels) {
        *pixel = Rgb([
            ((channels[0].clamp(-1.0, 1.0) + 1.0) * 127.5).round() as u8,
            ((channels[1].clamp(-1.0, 1.0) + 1.0) * 127.5).round() as u8,
            ((channels[2].clamp(-1.0, 1.0) + 1.0) * 127.5).round() as u8,
        ]);
    }
    output.save(&args.output)?;
    println!(
        "backend={} size={}x{} denoise_compile_ms={denoise_compile_ms:.3} denoise_ms={denoise_ms:.3} vae_compile_ms={vae_compile_ms:.3} decode_ms={decode_ms:.3} output={}",
        client.info()?.platform,
        args.width,
        args.height,
        args.output.display(),
    );
    Ok(())
}

fn main() -> Result<()> {
    run(Args::parse())
}
